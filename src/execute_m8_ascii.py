# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# PHASE 8.1 ??? Optuna Hyperparameter Optimisation (Train ??? 2024 only)
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
print("\n?????? Phase 8.1: Optuna HPO ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????")

params_path = config.RESULTS_MODELS_DIR / "optuna_best_params.json"
hpo_rows = []
if params_path.exists():
    with open(params_path, "r") as f:
        optuna_results = json.load(f)
    print(f"  [RESUME] Loaded {len(optuna_results)} already completed studies from {params_path}")
    for k, v in optuna_results.items():
        row = {"model": v["model"], "problem": v["problem"], "cv_huber": v["best_cv_huber"]}
        row.update(v["best_params"])
        hpo_rows.append(row)
else:
    optuna_results = {}

for prob in PROBLEMS:
    for model_name in CHAMPIONS:
        key = f"{model_name}_{prob}"
        if key in optuna_results:
            print(f"  [SKIP] {key} already tuned -> Best CV Huber: {optuna_results[key]['best_cv_huber']:.5f}")
            continue
        print(f"\n  Tuning {model_name} / {prob} ...", flush=True)
        t0 = time.time()
        res = tune_dl_model(model_name, prob, n_trials=35, n_splits=3, seed=42)
        elapsed = time.time() - t0
        optuna_results[key] = res
        print(f"  Best CV Huber: {res['best_cv_huber']:.5f} ({elapsed:.0f}s)")
        print(f"    Params: {res['best_params']}")
        hpo_rows.append({
            "model": model_name, "problem": prob,
            "cv_huber": res["best_cv_huber"],
            **res["best_params"],
        })
        with open(params_path, "w") as f:
            json.dump(optuna_results, f, indent=2)
        import pandas as pd
        pd.DataFrame(hpo_rows).to_csv(config.RESULTS_TABLES_DIR / "m8_hpo_results.csv", index=False)

# # PHASE 8.2 ??? Retrain tuned models on full train, evaluate on 2025 val
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
print("\n?????? Phase 8.2: Retrain Tuned Champions ????????????????????????????????????????????????????????????????????????????????????")

tuned_models    = {}   # {model_prob: nn.Module}
tuned_preds     = {}   # {model_prob: np.ndarray MW}
tuned_data      = {}   # {prob: data_dict}
tuned_metrics   = []

for prob in PROBLEMS:
    for model_name in CHAMPIONS:
        key = f"{model_name}_{prob}"
        if key not in optuna_results:
            continue
        best_p = optuna_results[key]["best_params"]
        print(f"\n  Retraining {model_name}/{prob} with tuned params...", flush=True)

        model, metrics, data, preds_mw = retrain_tuned_model(
            model_name, prob, best_p, epochs=35, patience=7
        )
        tuned_models[key] = model
        tuned_preds[key]  = preds_mw
        tuned_data[prob]  = data

        # Save checkpoint
        ckpt_path = config.RESULTS_MODELS_DIR / f"tuned_{key}.pt"
        torch.save(model.state_dict(), ckpt_path)

        # Save predictions
        y_val_mw = data["y_val_mw"][:len(preds_mw)]
        pred_df  = pd.DataFrame({
            "timestamp":    data["val_ts"][:len(preds_mw)],
            "y_true":       y_val_mw,
            "y_pred_tuned": preds_mw,
            "problem":      prob,
            "model":        model_name,
        })
        pred_path = config.RESULTS_PREDICTIONS_DIR / f"tuned_{key}_val_predictions.parquet"
        pred_df.to_parquet(pred_path, index=False)

        row = {"model": model_name, "problem": prob}
        row.update({k: v for k, v in metrics.items() if isinstance(v, (int, float))})
        tuned_metrics.append(row)
        rmse_val = metrics.get("rmse", float("nan"))
        print(f"  ??? Tuned RMSE={rmse_val:.2f} MW  Skill={metrics.get('skill_vs_persistence', 0):.1f}%")

tuned_metrics_df = pd.DataFrame(tuned_metrics)
tuned_metrics_df.to_csv(config.RESULTS_TABLES_DIR / "m8_tuned_model_metrics.csv", index=False)
print(f"\nTuned model metrics ??? results/tables/m8_tuned_model_metrics.csv")

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# PHASE 8.3 ??? Probabilistic Forecasting (Quantile LightGBM)
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
print("\n?????? Phase 8.3: Probabilistic Forecasting ??????????????????????????????????????????????????????????????????????????????")

prob_rows = []
for prob in PROBLEMS:
    print(f"\n  Quantile LightGBM / {prob} ...", flush=True)
    X_tr, y_tr, X_va, y_va = load_flat_features(prob)
    q_models, q_preds, q_metrics = train_quantile_lgbm(X_tr, y_tr, X_va, y_va)

    # Save interval predictions
    int_df = pd.DataFrame({
        "y_true": y_va,
        "p10":    q_preds[0.10],
        "p50":    q_preds[0.50],
        "p90":    q_preds[0.90],
        "problem": prob,
    })
    int_df.to_parquet(config.RESULTS_PREDICTIONS_DIR / f"quantile_lgbm_{prob}_val.parquet", index=False)

    cov  = q_metrics.get("coverage_80pct", float("nan"))
    pin  = q_metrics.get("pinball_q50", float("nan"))
    iw   = q_metrics.get("interval_width", float("nan"))
    print(f"  ??? P50 Pinball={pin:.2f}  Coverage@80%={cov*100:.1f}%  Width={iw:.1f} MW")

    row = {"problem": prob}
    row.update(q_metrics)
    prob_rows.append(row)

    # Plot uncertainty fan
    fig, ax = plt.subplots(figsize=(12, 4))
    n_plot  = min(720, len(y_va))
    x       = range(n_plot)
    ax.fill_between(x, q_preds[0.10][:n_plot], q_preds[0.90][:n_plot],
                    alpha=0.25, label="80% PI (P10???P90)", color="steelblue")
    ax.plot(x, q_preds[0.50][:n_plot], color="steelblue", linewidth=1.2, label="P50 Median")
    ax.plot(x, y_va[:n_plot], color="crimson", linewidth=0.8, alpha=0.8, label="Actual MW")
    ax.set_title(f"Probabilistic Forecast ??? {prob} (Quantile LightGBM, first 30 days)")
    ax.set_xlabel("Hour"); ax.set_ylabel("MW")
    ax.legend(fontsize=8); plt.tight_layout()
    fig.savefig(FIGS_DIR / f"prob_forecast_{prob}.png", dpi=120)
    plt.close(fig)

prob_df = pd.DataFrame(prob_rows)
prob_df.to_csv(config.RESULTS_TABLES_DIR / "m8_probabilistic_metrics.csv", index=False)

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# PHASE 8.4 ??? Formal Ensemble Implementations & Comparison
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
print("\n?????? Phase 8.4: Formal Ensembles ?????????????????????????????????????????????????????????????????????????????????????????????????????????")

ensemble_rows  = []
seasonal_rows  = []

for prob in PROBLEMS:
    print(f"\n  Problem: {prob}")
    data = tuned_data[prob]

    # Collect tuned predictions per model
    champ_preds: dict[str, np.ndarray] = {}
    y_val_mw = None
    for m in CHAMPIONS:
        key = f"{m}_{prob}"
        if key in tuned_preds:
            p = tuned_preds[key]
            d = tuned_data[prob]
            yt = d["y_val_mw"][:len(p)]
            if y_val_mw is None: y_val_mw = yt
            min_len = min(len(yt), len(p))
            champ_preds[m] = p[:min_len]

    if y_val_mw is None:
        print("  No predictions ??? skipping."); continue
    min_len  = min(len(y_val_mw), min(len(p) for p in champ_preds.values()))
    y_val_mw = y_val_mw[:min_len]
    for m in champ_preds: champ_preds[m] = champ_preds[m][:min_len]

    timestamps = pd.to_datetime(data["val_ts"][:min_len])

    # Method 1: Equal-weight
    y_eq = equal_weight_average(champ_preds)
    m1   = ensemble_metrics(y_val_mw, y_eq, prob, "equal_weight")
    ensemble_rows.append(m1)
    seasonal_rows.append(walk_forward_seasonal(y_val_mw, y_eq, timestamps, prob, "equal_weight"))
    print(f"  Equal-weight RMSE={m1['rmse']:.2f}  Skill={m1['skill_vs_persistence']:.1f}%")

    # Method 2: NNLS
    y_nn, weights_nn = nnls_weighted_average(y_val_mw, champ_preds)
    m2 = ensemble_metrics(y_val_mw, y_nn, prob, "nnls")
    ensemble_rows.append(m2)
    seasonal_rows.append(walk_forward_seasonal(y_val_mw, y_nn, timestamps, prob, "nnls"))
    print(f"  NNLS       RMSE={m2['rmse']:.2f}  Skill={m2['skill_vs_persistence']:.1f}%")
    print(f"    Weights: { {k: f'{v*100:.1f}%' for k,v in weights_nn.items() if v > 0.005} }")

    # Method 3: Stacking Ridge
    y_st, meta = stacking_ridge(y_val_mw, champ_preds)
    m3 = ensemble_metrics(y_val_mw, y_st, prob, "stacking_ridge")
    ensemble_rows.append(m3)
    seasonal_rows.append(walk_forward_seasonal(y_val_mw, y_st, timestamps, prob, "stacking_ridge"))
    print(f"  Stacking   RMSE={m3['rmse']:.2f}  Skill={m3['skill_vs_persistence']:.1f}%")

    # Method 4: Residual Hybrid (DLinear base + GRU correction)
    if "dlinear" in champ_preds and "gru" in champ_preds:
        y_hy, best_a = residual_hybrid(y_val_mw, champ_preds["dlinear"], champ_preds["gru"])
        m4 = ensemble_metrics(y_val_mw, y_hy, prob, f"residual_hybrid(a={best_a:.2f})")
        ensemble_rows.append(m4)
        seasonal_rows.append(walk_forward_seasonal(y_val_mw, y_hy, timestamps, prob, "residual_hybrid"))
        print(f"  Resid.Hyb  RMSE={m4['rmse']:.2f}  Skill={m4['skill_vs_persistence']:.1f}%  alpha={best_a:.2f}")

    # Individual best (NNLS champion for reference)
    best_single_rmse = min(
        __import__("src.ensemble", fromlist=["_rmse"])._rmse(y_val_mw, p)
        for p in champ_preds.values()
    )

    # Save NNLS predictions
    ens_df = pd.DataFrame({
        "y_true":       y_val_mw,
        "y_pred_equal": y_eq,
        "y_pred_nnls":  y_nn,
        "y_pred_stack": y_st,
        "problem":      prob,
    })
    ens_df.to_parquet(config.RESULTS_PREDICTIONS_DIR / f"ensemble_{prob}_val.parquet", index=False)

    # Save NNLS weights
    weights_path = config.RESULTS_MODELS_DIR / f"nnls_weights_{prob}.json"
    with open(weights_path, "w") as f:
        json.dump(weights_nn, f, indent=2)

    # Plot: Ensemble comparison (first 168h = 1 week)
    fig, axes = plt.subplots(2, 1, figsize=(14, 7), sharex=True)
    n_p = min(168, min_len)
    xr  = range(n_p)
    axes[0].plot(xr, y_val_mw[:n_p], "k-", linewidth=1.2, label="Actual")
    axes[0].plot(xr, y_nn[:n_p], "b-", linewidth=1.0, alpha=0.85, label=f"NNLS (RMSE={m2['rmse']:.1f})")
    axes[0].plot(xr, y_eq[:n_p], "g--", linewidth=0.9, alpha=0.75, label=f"Equal-W (RMSE={m1['rmse']:.1f})")
    axes[0].set_title(f"{prob} ??? Ensemble Forecast (1 week)"); axes[0].legend(fontsize=8)
    axes[0].set_ylabel("MW")

    residuals = y_val_mw[:n_p] - y_nn[:n_p]
    axes[1].bar(xr, residuals, color=["crimson" if r > 0 else "steelblue" for r in residuals], alpha=0.6)
    axes[1].axhline(0, color="black", linewidth=0.8)
    axes[1].set_title("NNLS Residuals (MW)"); axes[1].set_ylabel("MW"); axes[1].set_xlabel("Hour")
    plt.tight_layout()
    fig.savefig(FIGS_DIR / f"ensemble_comparison_{prob}.png", dpi=120)
    plt.close(fig)

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
