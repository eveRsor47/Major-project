PROBLEMS  = ["S1", "S24", "D1", "D24"]
CHAMPIONS = ["bilstm", "gru", "cnn_lstm", "dlinear", "lstm"]

FIGS_DIR  = config.RESULTS_FIGURES_DIR / "m8_ensemble"
FIGS_DIR.mkdir(parents=True, exist_ok=True)

print("=" * 70)
print("MILESTONE M8 ??? Tuning, Probabilistic Models & Ensembles")
