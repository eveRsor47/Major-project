print("\n?????? Phase 8.5: Save Results ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????")

ens_df    = pd.DataFrame(ensemble_rows)
seas_df   = pd.concat(seasonal_rows, ignore_index=True)

ens_df.to_csv(config.RESULTS_TABLES_DIR / "m8_ensemble_results.csv", index=False)
seas_df.to_csv(config.RESULTS_TABLES_DIR / "m8_seasonal_results.csv", index=False)

print("\n  Ensemble Results:")
print(ens_df[["problem", "method", "rmse", "skill_vs_persistence"]].to_string(index=False))

print("\n  Seasonal Breakdown (NNLS):")
nnls_seas = seas_df[seas_df["method"] == "nnls"][["problem", "season", "rmse", "skill"]].sort_values(["problem", "season"])
print(nnls_seas.to_string(index=False))

