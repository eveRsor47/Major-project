torch.set_num_threads(min(8, __import__("os").cpu_count() or 4))

from src import config
from src.tuning import tune_dl_model, retrain_tuned_model
from src.ensemble import (
    equal_weight_average,
    nnls_weighted_average,
    stacking_ridge,
    residual_hybrid,
    ensemble_metrics,
    walk_forward_seasonal,
    PERSISTENCE_RMSE,
)
